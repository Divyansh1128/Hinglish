"""POST-HOC PLANNING CHECK: re-score stored Pilot-B outputs with numeric_literal_v2.

Not a Pilot-B result and not part of any pre-registered Pilot-B analysis. It checks the
planning proxy quoted in phase2/PREREGISTRATION.md section 4 (Qwen3-4B E/R/C 69/61/67 vs
v1 51/58/58). Inputs are the stored outputs (results/pilot_b/audit/*_outputs_for_audit.jsonl),
the frozen Pilot-B gold (pilot_b/pilot_b_families.v2.json) and the stored per-rendering rows
(results/pilot_b/<model>/per_rendering.csv), which are used to confirm that v1 recomputed
here equals the stored v1 and that strict scores are the stored ones. No generation.

Usage from the repository root: python3 -B -m secondary_analysis.rescore_pilot_b_v2
"""
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

from secondary_analysis import numeric_endpoint as v1
from secondary_analysis import numeric_literal_v2 as v2

ROOT = Path(__file__).resolve().parents[1]
MODELS = ("qwen3-4b", "qwen3-8b", "llama-3.2-3b")
FORMS = ("E", "R", "C")
PROXY = {"qwen3-4b": {"v1": (51, 58, 58), "v2": (69, 61, 67)}}
OUTPUT = ROOT / "results" / "pilot_b" / "numeric_v2_rescore.md"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load(model):
    """Rows: rendering_id, family_id, form, response, truncated, gold, strict, stored_v1."""
    gold = {f["family_id"]: f["gold"] for f in json.loads((ROOT / "pilot_b/pilot_b_families.v2.json").read_text("utf-8"))}
    with (ROOT / "results/pilot_b" / model / "per_rendering.csv").open(newline="", encoding="utf-8") as stream:
        stored = {r["rendering_id"]: r for r in csv.DictReader(stream)}
    rows = []
    for line in (ROOT / "results/pilot_b/audit" / f"{model}_outputs_for_audit.jsonl").read_text("utf-8").splitlines():
        item = json.loads(line)
        row = stored[item["rendering_id"]]
        if (row["family_id"], row["form"]) != (item["family_id"], item["form"]):
            raise ValueError("audit/per_rendering mismatch")
        rows.append(dict(rendering_id=item["rendering_id"], family_id=item["family_id"], form=item["form"],
                         response=item["model_output"], truncated=bool(item["truncated"]),
                         gold=gold[item["family_id"]], strict=row["correct"] == "True",
                         stored_v1=row["numeric_correct"] == "True"))
    if len(rows) != len(stored) or len({r["rendering_id"] for r in rows}) != len(rows):
        raise ValueError("incomplete or duplicated outputs for " + model)
    return rows


def rescore(model):
    rows = load(model)
    table = {e: Counter() for e in ("strict", "v1", "v2")}
    changed, reasons = [], Counter()
    for r in rows:
        a = v1.evaluate_numeric(r["response"], r["gold"], r["truncated"])
        b = v2.evaluate_numeric(r["response"], r["gold"], r["truncated"])
        if a["correct"] != r["stored_v1"]:
            raise ValueError(f"recomputed v1 differs from stored v1 for {model} {r['rendering_id']}")
        table["strict"][r["form"]] += r["strict"]
        table["v1"][r["form"]] += a["correct"]
        table["v2"][r["form"]] += b["correct"]
        if a["correct"] != b["correct"] or a["status"] != b["status"]:
            if not v2.gold_is_rupees(r["gold"]):
                raise ValueError(f"v2 differs from v1 on non-rupee gold: {model} {r['rendering_id']}")
            changed.append((r["rendering_id"], a["status"], b["status"], b["extraction_path"], b["correct"]))
        if v2.uses_new_path(b):
            reasons[(b["extraction_path"].split("|")[-1], b["status"])] += 1
    return dict(n=len(rows) // 3, table=table, changed=changed, paths=reasons,
                rupee_families=len({r["family_id"] for r in rows if v2.gold_is_rupees(r["gold"])}))


def report():
    results = {m: rescore(m) for m in MODELS}
    lines = ["# numeric_literal_v2 re-score of stored Pilot-B outputs — POST-HOC PLANNING CHECK", "",
             "**Post hoc, planning only.** This is not a Pilot-B result and not part of the Pilot-B pre-registration. "
             "It applies `numeric_literal_v2` (phase2/PREREGISTRATION.md §4, D040) to the stored Pilot-B outputs to "
             "check the planning proxy quoted in the Phase-2 pre-registration. Strict accuracy (scorer v1.0.0) is the "
             "stored primary score and is unchanged; no output was regenerated.", "",
             "Generated by `python3 -B -m secondary_analysis.rescore_pilot_b_v2`.", "",
             "Inputs (SHA-256):", ""]
    paths = ["secondary_analysis/numeric_endpoint.py", "secondary_analysis/numeric_literal_v2.py",
             "pilot_b/pilot_b_families.v2.json"] + \
            [f"results/pilot_b/audit/{m}_outputs_for_audit.jsonl" for m in MODELS] + \
            [f"results/pilot_b/{m}/per_rendering.csv" for m in MODELS]
    lines += [f"- `{p}` `{sha(ROOT / p)}`" for p in paths]
    lines += ["", "Recomputed v1 equals the stored `numeric_correct` on all 630 renderings.", "",
              "| Model | Families | Rupee-gold families | Strict E/R/C | v1 E/R/C | v2 E/R/C | v2 − v1 |",
              "|---|---:|---:|---|---|---|---|"]
    for m, res in results.items():
        t = res["table"]
        fmt = lambda e: "/".join(str(t[e][f]) for f in FORMS)
        diff = "/".join(f"{t['v2'][f] - t['v1'][f]:+d}" for f in FORMS)
        lines.append(f"| {m} | {res['n']} | {res['rupee_families']} | {fmt('strict')} | {fmt('v1')} | {fmt('v2')} | {diff} |")
    q = results["qwen3-4b"]["table"]
    got = {e: tuple(q[e][f] for f in FORMS) for e in ("v1", "v2")}
    proxy = PROXY["qwen3-4b"]
    lines += ["", "## Comparison with the pre-registered proxy (Qwen3-4B)", "",
              f"- Pre-registration (§4): v1 {'/'.join(map(str, proxy['v1']))}, v2 {'/'.join(map(str, proxy['v2']))}.",
              f"- This re-score: v1 {'/'.join(map(str, got['v1']))}, v2 {'/'.join(map(str, got['v2']))}.",
              f"- **{'Matches' if got == proxy else 'Does not match'}** the quoted proxy."]
    lines += ["", "## Renderings whose numeric status changes (v1 → v2)", ""]
    for m, res in results.items():
        lines += [f"### {m}", "", f"{len(res['changed'])} changed; new-path uses by (path, v2 status): "
                  + (", ".join(f"{p} {s}: {n}" for (p, s), n in sorted(res["paths"].items())) or "none"), ""]
        if res["changed"]:
            lines += ["| Rendering | v1 status | v2 status | v2 path | v2 correct |", "|---|---|---|---|---|"]
            lines += [f"| {rid} | {a} | {b} | `{p}` | {c} |" for rid, a, b, p, c in res["changed"]]
            lines.append("")
    lines += ["Every changed rendering has rupee gold (INR); v2 changes nothing elsewhere "
              "(checked in `secondary_analysis/tests/test_numeric_literal_v2.py`).", ""]
    return "\n".join(lines), results


def main():
    text, _ = report()
    OUTPUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
